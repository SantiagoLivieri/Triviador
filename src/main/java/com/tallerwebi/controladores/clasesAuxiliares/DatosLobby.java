package com.tallerwebi.controladores.clasesAuxiliares;

/**
 * Datos del formulario para iniciar una partida local.
 */
public class DatosLobby {

  private String nombreJugadorUno;
  private String colorJugadorUno;

  private String nombreJugadorDos;
  private String colorJugadorDos;

  private String nombreJugadorTres;
  private String colorJugadorTres;

  public String getNombreJugadorUno() {
    return nombreJugadorUno;
  }

  public void setNombreJugadorUno(String nombreJugadorUno) {
    this.nombreJugadorUno = nombreJugadorUno;
  }

  public String getColorJugadorUno() {
    return colorJugadorUno;
  }

  public void setColorJugadorUno(String colorJugadorUno) {
    this.colorJugadorUno = colorJugadorUno;
  }

  public String getNombreJugadorDos() {
    return nombreJugadorDos;
  }

  public void setNombreJugadorDos(String nombreJugadorDos) {
    this.nombreJugadorDos = nombreJugadorDos;
  }

  public String getColorJugadorDos() {
    return colorJugadorDos;
  }

  public void setColorJugadorDos(String colorJugadorDos) {
    this.colorJugadorDos = colorJugadorDos;
  }

  public String getNombreJugadorTres() {
    return nombreJugadorTres;
  }

  public void setNombreJugadorTres(String nombreJugadorTres) {
    this.nombreJugadorTres = nombreJugadorTres;
  }

  public String getColorJugadorTres() {
    return colorJugadorTres;
  }

  public void setColorJugadorTres(String colorJugadorTres) {
    this.colorJugadorTres = colorJugadorTres;
  }
}
